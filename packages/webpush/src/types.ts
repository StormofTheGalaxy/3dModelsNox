/**
 * Веб-пуши как четвёртый канал уведомлений (§4.7, post-MVP №8).
 *
 * Наружу торчит одна операция: отправить сообщение в подписку браузера.
 * Подписка живёт на устройстве и протухает сама — поэтому результат
 * отличает «не доставили» от «подписки больше нет», и вызывающий код по
 * второму признаку её удаляет.
 */

/** Подписка ровно в том виде, в каком её отдаёт браузер. */
export interface WebPushSubscription {
  endpoint: string;
  /** Публичный ключ устройства, base64url. */
  p256dh: string;
  /** Секрет аутентификации подписки, base64url. */
  auth: string;
}

export interface WebPushMessage {
  /** Уже собранный заголовок на языке получателя. */
  title: string;
  body: string;
  /** Путь внутри приложения с языковым префиксом: куда вести по клику. */
  url: string;
  /**
   * Ключ схлопывания. Одинаковый тег заменяет прошлое уведомление вместо
   * того, чтобы копиться стопкой: десять «новых откликов» на экране
   * блокировки — это не десять поводов, а один.
   */
  tag?: string;
}

export interface WebPushSendResult {
  ok: boolean;
  /**
   * Браузер ответил 404 или 410: подписка отозвана — переустановили
   * приложение, очистили данные сайта, сменили устройство.
   */
  expired: boolean;
  error?: string;
}

export interface WebPushProvider {
  /** Настоящая отправка или заглушка. UI честно говорит, что это заглушка. */
  readonly isLive: boolean;

  /** Публичный ключ VAPID — его браузер требует при подписке. */
  readonly publicKey: string;

  send(subscription: WebPushSubscription, message: WebPushMessage): Promise<WebPushSendResult>;
}
